//! Render `index.md`: a generated, human-readable tree of everything open,
//! grouped by context, with derived annotations. Obsidian navigates it via
//! wikilinks; the daemon overwrites it on every mutation.

use std::fmt::Write;

use jiff::{ToSpan, Zoned};

use crate::action::derive;
use crate::humanize;
use crate::model::{Context, Status, Task};
use crate::tree::Tree;

const DONE_WINDOW_DAYS: i64 = 14;

pub fn render(tree: &Tree, now: &Zoned) -> String {
    let mut out = String::new();
    out.push_str("# Todo\n\n");
    out.push_str("_Generated by taskstaka. Edits here are overwritten; edit the notes instead._\n");

    for ctx in [Context::Work, Context::Personal] {
        let roots: Vec<&Task> = tree
            .roots()
            .into_iter()
            .filter(|t| t.context == ctx && t.status.is_open() && t.status != Status::Someday)
            .collect();
        let _ = write!(out, "\n## {}\n\n", title_case(ctx.as_str()));
        if roots.is_empty() {
            out.push_str("_nothing open_\n");
        }
        for r in roots {
            render_subtree(&mut out, tree, r, now, 0, true);
        }
    }

    let someday: Vec<&Task> = tree
        .roots()
        .into_iter()
        .filter(|t| t.status == Status::Someday)
        .collect();
    if !someday.is_empty() {
        out.push_str("\n## Someday\n\n");
        for r in someday {
            render_subtree(&mut out, tree, r, now, 0, true);
        }
    }

    let cutoff = now.timestamp() - (DONE_WINDOW_DAYS * 24 * 3600).seconds();
    let mut done: Vec<&Task> = tree
        .roots()
        .into_iter()
        .filter(|t| t.status.is_closed() && t.completed.is_some_and(|c| c >= cutoff))
        .collect();
    done.sort_by_key(|t| std::cmp::Reverse(t.completed));
    if !done.is_empty() {
        let _ = write!(out, "\n## Done (last {DONE_WINDOW_DAYS} days)\n\n");
        for r in done {
            render_subtree(&mut out, tree, r, now, 0, false);
        }
    }
    out
}

fn render_subtree(
    out: &mut String,
    tree: &Tree,
    task: &Task,
    now: &Zoned,
    depth: usize,
    annotate: bool,
) {
    let indent = "  ".repeat(depth);
    let mark = match task.status {
        Status::Todo | Status::Waiting | Status::Someday => " ",
        Status::Doing => "/",
        Status::Done => "x",
        Status::Dropped => "-",
    };
    let _ = write!(
        out,
        "{indent}- [{mark}] [[{}|{}]]",
        task.file_stem(),
        escape_link_text(&task.title)
    );
    if annotate && task.status.is_open() {
        let notes = annotations(tree, task, now);
        if !notes.is_empty() {
            let _ = write!(out, " — {}", notes.join(" · "));
        }
    }
    out.push('\n');
    for child in tree.children(&task.id) {
        render_subtree(out, tree, child, now, depth + 1, annotate);
    }
}

fn annotations(tree: &Tree, task: &Task, now: &Zoned) -> Vec<String> {
    let today = now.date();
    let ts = now.timestamp();
    let d = derive(tree, task, today);
    let mut notes = Vec::new();
    match task.status {
        Status::Doing => notes.push(format!(
            "▶ doing {}",
            humanize::since(task.started.unwrap_or(task.created), ts)
        )),
        Status::Waiting => {
            let mut s = format!(
                "⌛ waiting on {}",
                task.waiting_on.as_deref().unwrap_or("?")
            );
            if let Some(u) = task.until {
                let _ = write!(s, " until {u}");
            }
            notes.push(s);
        }
        Status::Someday => notes.push("💤 someday".into()),
        _ => {}
    }
    if let Some(w) = &d.waiting_on_summary {
        notes.push(format!(
            "⌛ waiting on {} · {}",
            w.person,
            humanize::since(w.since, ts)
        ));
    } else if d.blocked_by > 0 {
        notes.push(format!("⏳ blocked by {}", d.blocked_by));
    }
    if d.resurfaced_at.is_some() {
        notes.push("🔁 resurfaced".into());
    }
    if d.orphaned {
        notes.push("⚠ parent finished".into());
    }
    if let Some(due) = task.due {
        if due < today {
            notes.push(format!("⚠ overdue {due}"));
        } else {
            notes.push(format!("📅 due {due}"));
        }
    }
    if let Some(p) = task.priority {
        notes.push(format!("priority {p}"));
    }
    notes.push(format!("⏱ {}", humanize::since(task.created, ts)));
    notes
}

fn escape_link_text(s: &str) -> String {
    s.replace('|', "-").replace(['[', ']'], "")
}

fn title_case(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::TaskId;
    use jiff::Timestamp;

    #[test]
    fn snapshot() {
        let now: Zoned = "2026-09-29T15:00:00[UTC]".parse().unwrap();
        let at = |h: i64| now.timestamp() - (h * 3600).seconds();
        let mk = |id: &str, title: &str, parent: Option<&str>, status: Status, h: i64| {
            let mut t = Task::new(id.parse::<TaskId>().unwrap(), title, Context::Work, at(h));
            t.parent = parent.map(|p| p.parse().unwrap());
            t.status = status;
            if status == Status::Doing {
                t.started = Some(at(h));
            }
            if status.is_closed() {
                t.completed = Some(at(1));
            }
            t
        };
        let mut tasks = vec![
            mk("stry00", "Ship auth story", None, Status::Todo, 72),
            mk(
                "jwt000",
                "Fix JWT expiry",
                Some("stry00"),
                Status::Doing,
                48,
            ),
            mk(
                "m1gr00",
                "Write migration",
                Some("stry00"),
                Status::Todo,
                24,
            ),
            mk("01d000", "Old finished thing", None, Status::Done, 200),
            mk("1atr00", "Learn Zig", None, Status::Someday, 300),
            mk("wa1t00", "Renew passport", None, Status::Waiting, 96),
        ];
        tasks[5].context = Context::Personal;
        tasks[5].waiting_on = Some("Service Canada".into());
        tasks[5].until = Some(jiff::civil::date(2026, 10, 15));
        tasks[2].due = Some(jiff::civil::date(2026, 9, 20));
        let _: Timestamp = at(0);
        let tree = Tree::from_tasks(tasks);
        insta::assert_snapshot!(render(&tree, &now));
    }
}
